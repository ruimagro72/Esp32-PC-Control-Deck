void theme_apply(void) {
    GtkSettings *st = gtk_settings_get_default();
    if (st) g_object_set(st, "gtk-application-prefer-dark-theme", TRUE, NULL);
    GtkCssProvider *p = gtk_css_provider_new();
    GError *err = NULL;
    if (!gtk_css_provider_load_from_data(p, k_css, -1, &err)) {
        fprintf(stderr, "[theme] CSS error: %s\n", err ? err->message : "?");
        if (err) g_error_free(err);
    }
    GdkScreen *scr = gdk_screen_get_default();
    if (scr) gtk_style_context_add_provider_for_screen(scr, GTK_STYLE_PROVIDER(p), GTK_STYLE_PROVIDER_PRIORITY_USER);
    g_object_unref(p);
}
